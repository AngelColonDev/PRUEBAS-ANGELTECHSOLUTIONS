var serviceParams = new URLSearchParams(window.location.search);
var serviceKey = serviceParams.get('service') || 'diseno';
var service = serviceCatalog[serviceKey] || serviceCatalog.diseno;

function renderService() {
  var lang = (window.getLang ? window.getLang() : (localStorage.getItem('lang') || 'es'));
  document.title = service.title[lang] + ' | Angel Tech Solutions';
  document.getElementById('serviceTitle').textContent = service.title[lang];
  document.getElementById('serviceIntro').textContent = service.intro[lang];
  document.getElementById('serviceOutcome').textContent = service.outcome[lang];
  document.getElementById('quoteServiceBtn').href = 'index.html?service=' + encodeURIComponent(serviceKey) + '&openContact=1#contacto';
  document.getElementById('serviceIncludes').innerHTML = service.includes[lang].map(function(item) {
    return '<li class="flex items-start gap-2"><span class="iconify text-red-500 mt-0.5" data-icon="lucide:check" data-width="14" aria-hidden="true"></span><span>' + item + '</span></li>';
  }).join('');
  document.getElementById('serviceIdealFor').innerHTML = service.idealFor[lang].map(function(item) {
    return '<li class="flex items-start gap-2"><span class="iconify text-red-500 mt-0.5" data-icon="lucide:arrow-right" data-width="14" aria-hidden="true"></span><span>' + item + '</span></li>';
  }).join('');
  if (window.Iconify) Iconify.scan();
}

renderService();
document.addEventListener('langchange', renderService);
